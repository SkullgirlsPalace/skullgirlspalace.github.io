// Default language
let currentLanguage = localStorage.getItem('language') || 'pt-BR';

/**
 * Get current language
 * @returns {string} Current language code
 */
export function getCurrentLanguage() {
  return currentLanguage;
}

/**
 * Set language
 * @param {string} lang - Language code ('pt-BR' or 'en')
 */
export function setLanguage(lang) {
  if (translations[lang]) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang;
    // Dispatch event for components to re-render
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));

    // Update variant data translations if switching to English
    if (lang === 'en') {
      import('./dataTranslations.js').then(module => {
        module.updateVariantTranslations();
      }).catch(err => console.warn('Could not update variant translations:', err));
    } else {
      // Clear cache and reload page for PT-BR to show original data
      import('./dataTranslations.js').then(module => {
        module.clearTranslationCache();
        // Force re-render by dispatching event
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
      }).catch(() => {});
    }
  }
}

/**
 * Toggle between languages
 * @returns {string} New language code
 */
export function toggleLanguage() {
  const newLang = currentLanguage === 'pt-BR' ? 'en' : 'pt-BR';
  setLanguage(newLang);
  return newLang;
}

/**
 * Get translation by key path
 * @param {string} key - Dot-notation key (e.g., 'nav.home')
 * @param {object} vars - Variables for interpolation (optional)
 * @returns {string} Translated string
 */
export function t(key, vars = {}) {
  const keys = key.split('.');
  let value = translations[currentLanguage];

  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = value[k];
    } else {
      // Fallback to pt-BR if key not found in current language
      value = translations['pt-BR'];
      for (const fallbackKey of keys) {
        if (value && typeof value === 'object' && fallbackKey in value) {
          value = value[fallbackKey];
        } else {
          return key; // Return key if translation not found
        }
      }
      break;
    }
  }

  if (typeof value !== 'string') {
    return key;
  }

  // Interpolate variables
  let result = value;
  for (const [varKey, varValue] of Object.entries(vars)) {
    result = result.replace(new RegExp(`\\{${varKey}\\}`, 'g'), varValue);
  }

  return result;
}

/**
 * Get all translations for current language
 * @returns {object} All translations for current language
 */
export function getAllTranslations() {
  return translations[currentLanguage];
}
